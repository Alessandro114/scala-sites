export function t(key: string, locale: Locale = 'en', params?: Record<string, string | number>): string {
  let text = translations[locale]?.[key] || translations.en[key] || key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}

export function getLocaleFromHeader(acceptLanguage?: string): Locale {
  if (!acceptLanguage) return 'en'
  const locales: Locale[] = ['en', 'it', 'de', 'es', 'fr']
  for (const locale of locales) {
    if (acceptLanguage.toLowerCase().includes(locale)) return locale
  }
  return 'en'
}
